static unsigned crc_update(unsigned crc, const unsigned char* p, unsigned n) { while (n--) crc = g_crc_table[(crc ^ *p++) & 255u] ^ (crc >> 8); return crc; }
static unsigned char g_png_raw[6 << 20], g_png_out[6 << 20 | 1 << 19];
