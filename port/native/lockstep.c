static void png_put(const unsigned char* p, unsigned n) { while (n--) g_png_out[png_len++] = *p++; }
static void png_be32(unsigned v) { unsigned char b[4]; b[0] = (unsigned char)(v >> 24); b[1] = (unsigned char)(v >> 16); b[2] = (unsigned char)(v >> 8); b[3] = (unsigned char)v; png_put(b, 4); }
static void png_chunk(const char* type, const unsigned char* data, unsigned n) {
    unsigned char t[4]; unsigned crc;
    t[0] = (unsigned char)type[0]; t[1] = (unsigned char)type[1]; t[2] = (unsigned char)type[2]; t[3] = (unsigned char)type[3];
    png_be32(n); png_put(t, 4); if (n) png_put(data, n);
    crc = crc_update(0xffffffffu, t, 4); if (n) crc = crc_update(crc, data, n);
    png_be32(crc ^ 0xffffffffu);
}
/* rgb: w x h, 3 bytes per pixel; scale: nearest-neighbour magnification. Stored (uncompressed) deflate blocks: no libz needed. */
static int png_write(const char* path, const unsigned char* rgb, int w, int h, int scale) {
    static const unsigned char sig[8] = { 137, 80, 78, 71, 13, 10, 26, 10 };
    unsigned char ihdr[13]; unsigned raw_len = 0, pos, adler_a = 1, adler_b = 0, i; long fd;
    int x, y, sx, sy, W = w * scale, H = h * scale;
    if ((unsigned)H * (unsigned)(1 + 3 * W) > sizeof g_png_raw) return 0;
    for (y = 0; y < H; y++) {
        g_png_raw[raw_len++] = 0;
        for (x = 0; x < W; x++) { const unsigned char* p = rgb + 3 * ((y / scale) * w + x / scale); g_png_raw[raw_len++] = p[0]; g_png_raw[raw_len++] = p[1]; g_png_raw[raw_len++] = p[2]; }
    }
    (void)sx; (void)sy;
    png_len = 0; png_put(sig, 8);
    ihdr[0] = (unsigned char)(W >> 24); ihdr[1] = (unsigned char)(W >> 16); ihdr[2] = (unsigned char)(W >> 8); ihdr[3] = (unsigned char)W;
    ihdr[4] = (unsigned char)(H >> 24); ihdr[5] = (unsigned char)(H >> 16); ihdr[6] = (unsigned char)(H >> 8); ihdr[7] = (unsigned char)H;
    ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
    png_chunk("IHDR", ihdr, 13);
    {   /* IDAT: zlib header, stored blocks, adler32 -- written in place, the length and the CRC patched afterwards */
        unsigned start = png_len, plen;
        unsigned char* d;
        unsigned crc;
        png_be32(0); png_put((const unsigned char*)"IDAT", 4);
        d = g_png_out + png_len;
        plen = 0;
        d[plen++] = 0x78; d[plen++] = 0x01;
        for (pos = 0; pos < raw_len; ) {
            unsigned n = raw_len - pos > 65535u ? 65535u : raw_len - pos;
            d[plen++] = pos + n >= raw_len ? 1 : 0;
            d[plen++] = (unsigned char)n; d[plen++] = (unsigned char)(n >> 8); d[plen++] = (unsigned char)~n; d[plen++] = (unsigned char)(~n >> 8);
            for (i = 0; i < n; i++) d[plen++] = g_png_raw[pos + i];
            pos += n;
        }
        for (i = 0; i < raw_len; i++) { adler_a = (adler_a + g_png_raw[i]) % 65521u; adler_b = (adler_b + adler_a) % 65521u; }
        d[plen++] = (unsigned char)(adler_b >> 8); d[plen++] = (unsigned char)adler_b; d[plen++] = (unsigned char)(adler_a >> 8); d[plen++] = (unsigned char)adler_a;
        g_png_out[start] = (unsigned char)(plen >> 24); g_png_out[start + 1] = (unsigned char)(plen >> 16); g_png_out[start + 2] = (unsigned char)(plen >> 8); g_png_out[start + 3] = (unsigned char)plen;
        crc = crc_update(0xffffffffu, g_png_out + start + 4, 4 + plen) ^ 0xffffffffu;
        png_len += plen;
        png_be32(crc);
    }
    png_chunk("IEND", 0, 0);
    fd = sys3(5, (long)path, 0x241, 0x1a4);
    if (fd < 0) return 0;
    { unsigned off = 0; while (off < png_len) { long n = sys3(4, fd, (long)(g_png_out + off), (long)(png_len - off)); if (n <= 0) break; off += (unsigned)n; } }
    sys3(6, fd, 0, 0);
    return 1;
}
static unsigned parse_num(const char** pp) {
    const char* p = *pp;
    unsigned v = 0;
    while (*p == ' ' || *p == '\t') p++;
    if (p[0] == '0' && (p[1] == 'x' || p[1] == 'X')) { p += 2; while ((*p >= '0' && *p <= '9') || (*p >= 'a' && *p <= 'f') || (*p >= 'A' && *p <= 'F')) { v = v * 16 + (unsigned)(*p <= '9' ? *p - '0' : (*p | 32) - 'a' + 10); p++; } }
    else while (*p >= '0' && *p <= '9') { v = v * 10 + (unsigned)(*p - '0'); p++; }
    *pp = p;
    return v;
}
static void parse_path(const char** pp, char* dst, int max) {
    const char* p = *pp;
    int n = 0;
    while (*p == ' ' || *p == '\t') p++;
    while (*p && *p != '\n' && *p != '\r' && *p != ' ' && n < max - 1) dst[n++] = *p++;
    dst[n] = 0;
    *pp = p;
}
